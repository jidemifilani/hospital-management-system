import { InternalServerErrorException } from "@nestjs/common";
import { createReadStream } from "fs";
import { access, mkdir, stat, unlink, writeFile } from "fs/promises";
import { join, resolve, sep } from "path";
import { Readable } from "stream";
import { StorageDriver } from "./storage.driver";

/**
 * Local disk.
 *
 * Right for a single server with a volume mounted over the directory, and
 * wrong for anything where the filesystem does not outlive the process. The
 * root sits outside anything the web server serves, so a file is only ever
 * reachable through an endpoint that checks who is asking.
 */
export class LocalStorageDriver implements StorageDriver {
  readonly name = "local";

  constructor(private readonly root: string) {}

  /**
   * Resolves a key to an absolute path, refusing anything that escapes the
   * root.
   *
   * Keys are generated by this system, but a key also arrives from the
   * database on download, and a corrupted or tampered row must not be able to
   * read arbitrary files off the disk.
   */
  private pathFor(storageKey: string): string {
    const full = resolve(this.root, storageKey);
    if (full !== this.root && !full.startsWith(this.root + sep)) {
      throw new InternalServerErrorException("Refusing to read outside the document store");
    }
    return full;
  }

  async put(storageKey: string, buffer: Buffer): Promise<void> {
    const full = this.pathFor(storageKey);
    await mkdir(join(full, ".."), { recursive: true });
    await writeFile(full, buffer);
  }

  async exists(storageKey: string): Promise<boolean> {
    try {
      await access(this.pathFor(storageKey));
      return true;
    } catch {
      return false;
    }
  }

  async read(storageKey: string): Promise<Readable> {
    return createReadStream(this.pathFor(storageKey));
  }

  async sizeOf(storageKey: string): Promise<number> {
    return (await stat(this.pathFor(storageKey))).size;
  }

  async remove(storageKey: string): Promise<void> {
    await unlink(this.pathFor(storageKey));
  }
}
