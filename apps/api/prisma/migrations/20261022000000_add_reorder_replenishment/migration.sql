-- Odoo gap #4: automated reorder / replenishment

-- ReplenishmentSuggestionStatus enum
DO $$ BEGIN
  CREATE TYPE "ReplenishmentSuggestionStatus" AS ENUM ('PENDING', 'CONVERTED', 'DISMISSED');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- Reorder rules: one per item, triggers a suggestion when stock < minQty
CREATE TABLE IF NOT EXISTS reorder_rules (
  id               TEXT        NOT NULL PRIMARY KEY,
  "itemId"         TEXT        NOT NULL,
  "minQty"         INTEGER     NOT NULL,
  "maxQty"         INTEGER,
  "reorderQty"     INTEGER,
  "vendorName"     TEXT,
  "vendorContact"  TEXT,
  "vendorEmail"    TEXT,
  "leadTimeDays"   INTEGER     NOT NULL DEFAULT 0,
  "isActive"       BOOLEAN     NOT NULL DEFAULT TRUE,
  "lastTriggeredAt" TIMESTAMPTZ,
  "organizationId" TEXT        NOT NULL,
  "createdAt"      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt"      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_rr_item FOREIGN KEY ("itemId") REFERENCES inventory_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_rr_org  FOREIGN KEY ("organizationId") REFERENCES organizations(id)
);

CREATE INDEX IF NOT EXISTS rr_org_active_idx ON reorder_rules ("organizationId", "isActive");
CREATE INDEX IF NOT EXISTS rr_item_idx       ON reorder_rules ("itemId");

-- Replenishment suggestions generated by the engine
CREATE TABLE IF NOT EXISTS replenishment_suggestions (
  id               TEXT                             NOT NULL PRIMARY KEY,
  "ruleId"         TEXT                             NOT NULL,
  "itemId"         TEXT                             NOT NULL,
  "currentQty"     INTEGER                          NOT NULL,
  "minQty"         INTEGER                          NOT NULL,
  "suggestedQty"   INTEGER                          NOT NULL,
  status           "ReplenishmentSuggestionStatus"  NOT NULL DEFAULT 'PENDING',
  "purchaseOrderId" TEXT,
  "organizationId" TEXT                             NOT NULL,
  "triggeredAt"    TIMESTAMPTZ                      NOT NULL DEFAULT NOW(),
  CONSTRAINT fk_rs_rule FOREIGN KEY ("ruleId") REFERENCES reorder_rules(id) ON DELETE CASCADE,
  CONSTRAINT fk_rs_item FOREIGN KEY ("itemId") REFERENCES inventory_items(id),
  CONSTRAINT fk_rs_org  FOREIGN KEY ("organizationId") REFERENCES organizations(id)
);

CREATE INDEX IF NOT EXISTS rs_org_status_idx ON replenishment_suggestions ("organizationId", status);
